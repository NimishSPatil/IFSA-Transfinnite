"""
export_prompt2_docs.py - writes docs/PROMPT2_NOTES.md from the engine, so every number matches the dashboard.

    python code/export_prompt2_docs.py
"""
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "dashboard"))

from app.engine import controls as CT                 # noqa: E402
from app.engine import inventory as INV               # noqa: E402
from app.engine import inventory_iface as II          # noqa: E402
from app.engine import readme as RM                   # noqa: E402
from app.engine import risks as RK                    # noqa: E402
from app.engine import supply as SUP                  # noqa: E402

DOCS = ROOT / "docs"
CTL = CT.Ctl()
W0 = date(2026, 5, 4)


def md(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(x).replace("|", "/") for x in r) + " |" for r in rows]
    return "\n".join(out)


def cr(x):
    return f"₹{x / 1e7:,.2f} Cr"


def main():
    rc, sm, sa = INV.reconcile(), INV.summary("summer26", CTL), INV.summary("all", CTL)
    con, rep, ov = INV.conservation(), INV.replicate(), INV.overstock("all", CTL)
    lk, fc = INV.link("summer26", CTL), INV.forecast_compare("summer26", CTL)
    sim = SUP.balance(W0, CTL)["planned"]
    old = II.supply_to_fg(W0, CTL, sim)
    L = ["# PulpSense · Prompt 2 (Inventory integration) — notes and deliverables\n",
         "Generated by `code/export_prompt2_docs.py`. Acceptance: `code/check_prompt2.py` (8 checks, `docs/acceptance_prompt2.csv`); "
         "prompt-1 checks still run with `code/check_prompt1.py`.\n"]

    L.append("## 1. Change log\n")
    L.append("""- **Inventory data source**: the teammate's feed copied to `data/inventory_feed/` (`dashboard_data.json`, `dashboard_data_1.js`,
  `HANDOFF_dashboard_2.md`). The server reads the JSON; the `.js` payload (window.DASHBOARD_DATA) is checked to be identical.
- **New engine module** `engine/inventory.py`: reconciliation, live loss/transport recalculation, windows, heatmap, transfers,
  overstock and aging, stock-conservation check, greedy-replica match rate, forecast-source comparison, the Supply ↔ Inventory link,
  the demand-gated reallocation check and the READ_ME feed. Built on the prompt-1 hooks (`supply.balance`, `forecast.depot_forecast`,
  `reviews`, `readme`).
- **New pages** (sidebar group "Inventory module"): Rebalancing (with the reconciliation strip), Supply ↔ Inventory, Overstock & aging,
  Forecast source. The descriptive Inventory page now links to them; the "coming in prompt 2" placeholders are gone.
- **Control Panel**: group h (loss rates h01/h02, overstock threshold h03, write-off rate h05; h04/h06/h07 locked as optimiser-dependent),
  g08 finished-goods lag, f28 forecast source, f29 difference flag. Transit a07 (2–4 days, F49) reused. Controls whose default comes from the
  case *or the file* now show "departs from case" and go to READ_ME.
- **Transfers are review candidates** (Approve / Reject / Defer / Escalate, rationale required); "Supply chain manager" added as a role.
- **READ_ME** gains the inventory group, five open questions for the teammate, a forecast-source flag and a pending-transfers item.
  **Risk register** gains R28–R31.
- **Data & assumptions** has a "which source feeds which panel" table.
""")

    L.append("## 2. Reconciliation\n")
    L.append(md(["Figure", "Handoff", "File totals", "Recomputed from rows", "Agree"],
                [[r["name"], r["handoff"], round(r["file"], 4), round(float(r["recomputed"]), 4), "yes" if r["ok"] else "NO"] for r in rc["rows"]]))
    L.append(f"\n{rc['matched_rows']} of {rc['n_rows']} weekly rows reproduce exactly under ₹15.36 below P50 + ₹3.84 below P80. The exceptions are the "
             f"{len(rc['exceptions'])} unreported rows ({rc['exceptions'][0]['depot']}, week of {rc['exceptions'][0]['week']:%d %b %Y}): marked 'ok' yet "
             f"carrying {cr(rc['exc_loss'])}, which equals all of 2025's loss before rebalancing. Net by year: "
             + ", ".join(f"{y['year']} {y['net'] / 1e7:+.2f} Cr" for y in sa["years"]) + ".\n")
    L.append(f"Default window Mar–Jun 2026: loss before {cr(sm['before'])}, after {cr(sm['after'])} + transport {cr(sm['transport'])}, "
             f"net saving {cr(sm['saving'])}; **{100 * sm['pp_dp_share']:.2f}% of what is left is PP and DP** "
             f"({100 * sa['pp_dp_share']:.1f}% over the whole file) — a supply problem transfers cannot fix.\n")

    L.append("## 3. Decision tables\n")
    L.append("### 3.1 Rebalancer approach\n")
    L.append(md(["Approach", "Gives", "Against", "Verdict"], [
        ["Keep the 113 precomputed transfers", "Exact reconciliation; financial controls recalculate on them", "Optimiser settings not changeable", "**chosen**"],
        ["Transparent greedy replica (server-side)", "Re-runs under new thresholds",
         f"Reproduces {rep['exact'][0]}/{rep['exact'][1]} transfers (receivers {rep['receivers'][0]}/{rep['receivers'][1]}, senders "
         f"{rep['senders'][0]}/{rep['senders'][1]}), below the {rep['tolerance']:.0%} tolerance", "evidence only"],
        ["In-browser JavaScript greedy", "Client-side re-run", "Same rule and match rate; this dashboard renders on the server", "not needed"],
        ["Re-run the teammate's optimiser", "True what-ifs", "Offline, undocumented", "after the teammate answers"],
    ]))
    L.append("\nThe replica decodes the file's cover figures exactly (stock = last week's after-closing + receipts; demand = max of last week's "
             "sales and this week's P50: all 113 senders, 107/113 receivers) and finds the same shortage weeks (73/74), but the optimiser's "
             "sender choice is not a cover, stock, excess or region rule (only 11 of 113 transfers stay in-region). So h04, h06 and h07 are "
             "locked with a 'precomputed at default assumptions' badge.\n")
    L.append("### 3.2 Default window\n")
    L.append(md(["Window", "For", "Against", "Verdict"], [
        ["Mar–Jun 2026", "The case's summer (F18, F31); where the loss is", "Hides 2024–25 — so net-by-year is always shown", "**chosen**"],
        ["Whole file", "Matches handoff totals", "Mixes in two years of loss-making transfers", "one click"],
        ["Calendar 2026", "Year view", "Not the case's season", "one click"],
        ["Rolling to as-of", "Consistent with other pages", "The feed is a retrospective replay", "rejected"],
    ]))
    L.append("\n### 3.3 Forecast source\n")
    L.append(md(["Option", "For", "Against", "Verdict"], [
        ["File P50/P80 (default)", "Reconciles; the transfers were chosen on it", "Static; understates DP", "**chosen for the headline**"],
        ["Dashboard forecast (f28)", "Weekly; sees the DP spike", "Different loss definition; breaks reconciliation", "selectable, side by side"],
        ["Blend", "—", "Two definitions in one number", "rejected"],
    ]))
    L.append("\nSummer 2026, dashboard vs file P50: " + "; ".join(f"{r['sku']} {r['diff']:+.0%}" for r in fc["by_sku"] if r["diff"] is not None)
             + f". {len(fc['big'])} flavor-weeks differ by more than {CTL['f29']:.0%} (READ_ME).\n")

    L.append("## 4. READ_ME and risk register additions\n")
    rows = [x for x in RM.items(W0, CTL) if x["group"] in ("Inventory (prompt 2)", "Open questions (teammate)")]
    L.append(md(["Bucket", "Severity", "Item"], [[x["bucket"], x["severity"], x["title"]] for x in rows]))
    L.append("\n")
    rk = {r["id"]: r for r in RK.evaluate(W0, CTL)}
    L.append(md(["ID", "Risk", "Status (11 May 2026)", "Evidence"],
                [[i, RK.META[i]["name"], rk[i]["status"], rk[i]["evidence"]] for i in ("R28", "R29", "R30", "R31")]))
    L.append(f"\nOverstock: rebalancing raises over-{ov['thr']:.0f}-day depot-weeks from {ov['before']['status_n']} to {ov['after']['status_n']} "
             f"(file status) — mostly " + ", ".join(f"{d} {s} (+{n})" for d, s, n in ov["new"][:4]) + ". No rupee write-off is claimed unless h05 is set; "
             "the case's ₹6 Cr (F60) is not reproduced by this view.\n")
    L.append(f"Stock conservation: the replay creates {con['total']:,.0f} bottles; DP carries +{con['dp_mode']:,.0f} bottles a week from "
             f"{con['dp_from']:%d %b} to {con['dp_to']:%d %b %Y} (the brief said to 25 May; the data runs to the end of the file).\n")

    L.append("## 5. What the Inventory integration changes in the Supply module's numbers\n")
    L.append(md(["Item", "Prompt 1", "Prompt 2", "Why"], [
        ["Where PP stock runs out (closure replay, pooled)", f"{old['PP']['runs_out']:%d %b} (no lag)",
         f"{lk['proj']['PP']['runs_out']:%d %b} ({lk['lag']}-day lag, g08)", "production now reaches shelves after the finished-goods lag"],
        ["Pre-positioned passionfruit cover", "cost 'not quantified'; days protected only",
         f"{[x for x in lk['scen'] if x['name'].startswith('Pre-')][0]['unmet'] / 1e5:.1f} L bottles not made vs {lk['scen'][0]['unmet'] / 1e5:.1f} L",
         "now simulated in the daily balance (scenario output, not a saving)"],
        ["Valuing a missing bottle", "₹19.20 = d05 × d06 (contribution)", f"₹{lk['rate']:.2f} = h01 + h02 (file shortage rule)",
         "equal at defaults; now two controls, both shown and labelled"],
        ["Residual loss after rebalancing", "—", f"{cr(sm['pp_dp'])} PP + DP ({100 * sm['pp_dp_share']:.2f}%)", "attributed to Supply on one panel"],
        ["Pulp priority signal", "joint allocation by bottles only", f"DP below 1 day of depot cover in {len(lk['dp_zero'])} summer weeks",
         "Inventory → Supply signal for the g07 floor (not automatic)"],
        ["Reallocation gate", "none", "extra production must be depot-demand-backed within 30 − lag days", "C14, F38, F39"],
        ["Risk register", "27 risks", "31 risks (R28–R31)", "inventory feed risks"],
        ["Supply engine inputs", "v2 CSVs", "unchanged (v2 CSVs)", "the feed only drives inventory panels; they agree to ±1 bottle"],
    ]))
    L.append("\nThe Supply engine's own numbers (first unsafe days, options, co-packer rule, replays) are unchanged: it still reads the "
             "case-calibrated CSVs.\n")
    L.append("## 6. Open questions for the teammate (also on READ_ME)\n")
    L += [f"{i + 1}. {q}" for i, q in enumerate(INV.QUESTIONS)]
    (DOCS / "PROMPT2_NOTES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", DOCS / "PROMPT2_NOTES.md")


if __name__ == "__main__":
    main()
